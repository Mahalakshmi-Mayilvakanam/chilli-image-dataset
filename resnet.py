class CustomDataset(Dataset):
    def __init__(self, root_dir, transform=None):
        self.root_dir = root_dir
        self.transform = transform
        self.classes = sorted(os.listdir(root_dir))

    def __len__(self):
        return sum(len(files) for _, _, files in os.walk(self.root_dir))

    def __getitem__(self, idx):
        class_folders = [folder for folder in os.listdir(self.root_dir) if os.path.isdir(os.path.join(self.root_dir, folder))]
        class_idx = 0
        while idx >= len(os.listdir(os.path.join(self.root_dir, class_folders[class_idx]))):
            idx -= len(os.listdir(os.path.join(self.root_dir, class_folders[class_idx])))
            class_idx += 1
        class_name = class_folders[class_idx]
        img_name = os.listdir(os.path.join(self.root_dir, class_name))[idx]
        img_path = os.path.join(self.root_dir, class_name, img_name)
        image = Image.open(img_path)
        label = self.classes.index(class_name)
        if self.transform:
            image = self.transform(image)
        return image, label

